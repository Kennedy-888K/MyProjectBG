# Demonstração de listas e tuplas

# Para declarar as listas...
LISTA = []
LISTA_INTEIROS = [1, 2, 3, 4, 5]
LISTA_CARACTERES = ["Maçã", "Banana", "cereja"]
LISTA_MISTA = [1, "Olá", 3.14, True]

# Para declarar as tuplas...
TUPLA_SEMANA = ("Seguda", "Terça", "Quarta")
TUPLA_FIBONACCI = (1, 2, 3, 5, 8, 13, 21)

# Para acessar os elementos da lista...
print(LISTA_INTEIROS)
print(LISTA_CARACTERES[0])
print(LISTA_MISTA[1])
print(TUPLA_SEMANA[2])
print(TUPLA_FIBONACCI)
